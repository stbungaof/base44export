function pickFields(meta, body, reply) {
  if (!body || typeof body !== 'object' || Array.isArray(body)) {
    reply.code(400).send({ error: 'Body must be a JSON object' });
    return null;
  }
  const out = {};
  const unknown = [];
  for (const [k, v] of Object.entries(body)) {
    if (k in BUILTIN) continue;
    const col = Object.prototype.hasOwnProperty.call(meta.columns, k) ? meta.columns[k] : null;
    if (!col) unknown.push(k);
    else out[k] = col.json && v !== null && v !== undefined ? JSON.stringify(v) : v;
  }
  if (unknown.length) {
    reply.code(400).send({ error: 'Unknown field(s): ' + unknown.join(', ') });
    return null;
  }
  return out;
}

function buildWhere(meta, filterJson, reply, params) {
  if (!filterJson) return '';
  let f;
  try { f = JSON.parse(filterJson); } catch { reply.code(400).send({ error: 'q must be JSON' }); return null; }
  if (!f || typeof f !== 'object' || Array.isArray(f)) { reply.code(400).send({ error: 'q must be an object' }); return null; }
  const parts = [];
  for (const [k, v] of Object.entries(f)) {
    if (!(k in BUILTIN) && !Object.prototype.hasOwnProperty.call(meta.columns, k)) { reply.code(400).send({ error: 'Unknown field: ' + k }); return null; }
    if (v === null) parts.push(qi(k) + ' IS NULL');
    else if (typeof v === 'object') { reply.code(400).send({ error: 'Only equality filters are supported (field: ' + k + ')' }); return null; }
    else { params.push(v); parts.push(qi(k) + ' = $' + params.length); }
  }
  return parts.length ? ' WHERE ' + parts.join(' AND ') : '';
}

