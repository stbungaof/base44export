const SAFE_EXT = /^\.[A-Za-z0-9]{1,10}$/;

async function save(dir, stream, originalName) {
  const ext = path.extname(originalName || '');
  const name = crypto.randomUUID() + (SAFE_EXT.test(ext) ? ext.toLowerCase() : '');
  await pipeline(stream, fs.createWriteStream(path.join(dir, name), { flags: 'wx' }));
  return name;
}

