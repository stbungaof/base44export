import path from 'node:path';
import crypto from 'node:crypto';
import { pipeline } from 'node:stream/promises';

export const uploadsDir = path.resolve(process.env.UPLOADS_DIR || '/data/uploads');
export const privateDir = path.resolve(process.env.PRIVATE_DIR || '/data/private');
fs.mkdirSync(uploadsDir, { recursive: true });
