const INLINE_TYPES = { '.pdf': 'application/pdf', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.gif': 'image/gif', '.webp': 'image/webp', '.txt': 'text/plain; charset=utf-8' };
app.get('/api/files/private/:name', async (req, reply) => {
  const { name } = req.params;
  const { exp, sig } = req.query;
  if (!PRIVATE_NAME.test(name) || !sig || Number(exp) < Date.now() / 1000 || !safeEq(sig, hmac(name + '.' + exp))) {
    return reply.code(403).send({ error: 'Invalid or expired link' });
  }
  const file = path.join(privateDir, name);
  if (!fs.existsSync(file)) return reply.code(404).send({ error: 'File not found' });
  const type = INLINE_TYPES[path.extname(name)];
  return reply
    .header('x-content-type-options', 'nosniff')
    .header('content-type', type || 'application/octet-stream')
    .header('content-disposition', type ? 'inline' : 'attachment')
    .send(fs.createReadStream(file));
});

